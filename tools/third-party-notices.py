#!/usr/bin/env python3
"""Writes THIRD-PARTY-NOTICES.txt: Sentry Studio's own licence, then those of
the Rust crates built into it on any of its platforms, and of its fonts.

    python3 -I tools/third-party-notices.py            # write the file
    python3 -I tools/third-party-notices.py --check    # fail if it's stale

Crates are those reached from the app through normal dependencies (not build
or dev ones) for each release target. Each one's licence files come from
cargo's download of it, so build for every platform first (or `cargo fetch`).
To keep it readable:
- a crate offered under a choice of licences is used under one of them
  (MIT where offered, see PREFERRED), so only that licence is given;
- an MIT or Apache-2.0 text with the standard wording is reduced to its
  copyright lines and a pointer to one full copy of that standard text;
- any other text seen before (ignoring spacing) is referred to, not repeated.
"""
import hashlib
import json
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "THIRD-PARTY-NOTICES.txt")
TARGETS = ["aarch64-apple-darwin", "x86_64-apple-darwin", "x86_64-pc-windows-gnu", "x86_64-unknown-linux-gnu"]
LICENCE_PREFIXES = ("license", "licence", "copying", "notice", "unlicense", "copyright")
