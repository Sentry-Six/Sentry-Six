#!/usr/bin/env python3
# Generates src/crmath_tables.rs: the double-double constants crmath.rs uses
# (pi/2 split for range reduction, sin/cos of j/64, Taylor coefficients).
# Needs mpmath. Each constant is printed as exact f64 bits.
#   python3 tools/gen_crmath_tables.py > src/crmath_tables.rs
import struct
import mpmath

mpmath.mp.prec = 300


def bits(x):
    return struct.unpack('<Q', struct.pack('<d', x))[0]


def lit(x):
    return 'f64::from_bits(0x%016x)' % bits(x)


def dd(v):
    hi = float(v)
    lo = float(v - mpmath.mpf(hi))
    return hi, lo


def round_bits(v, nbits):
    # v rounded to a double with at most nbits significant bits
    m, e = mpmath.frexp(v)
    return float(mpmath.ldexp(mpmath.nint(mpmath.ldexp(m, nbits)), e - nbits))


pio2 = mpmath.pi / 2
p1 = round_bits(pio2, 33)
p2 = round_bits(pio2 - p1, 33)
p3 = round_bits(pio2 - p1 - p2, 33)
p4 = float(pio2 - p1 - p2 - p3)

out = []
out.append('// Generated by tools/gen_crmath_tables.py (mpmath, 300-bit). Do not edit.')
out.append('')
out.append('/// pi/2 = PIO2[0] + PIO2[1] + PIO2[2] + PIO2[3]; the first three have 33')
out.append('/// significant bits, so k * PIO2[i] is exact for |k| < 2^20.')
out.append('pub const PIO2: [f64; 4] = [%s, %s, %s, %s];' % tuple(lit(x) for x in (p1, p2, p3, p4)))
out.append('pub const TWO_OVER_PI: f64 = %s;' % lit(float(2 / mpmath.pi)))
out.append('')
N = 52
out.append('/// (sin(j/64), cos(j/64)) as double-doubles: [sin_hi, sin_lo, cos_hi, cos_lo].')
out.append('pub const SINCOS_J64: [[f64; 4]; %d] = [' % N)
for j in range(N):
    c = mpmath.mpf(j) / 64
    sh, sl = dd(mpmath.sin(c))
    ch, cl = dd(mpmath.cos(c))
    out.append('    [%s, %s, %s, %s],' % (lit(sh), lit(sl), lit(ch), lit(cl)))
out.append('];')
out.append('')
out.append('/// Taylor coefficients: S3 = -1/3!, S5 = 1/5!, S7 = -1/7!, C4 = 1/4!, C6 = -1/6!.')
for name, v in [
    ('S3', -1 / mpmath.mpf(6)),
    ('S5', 1 / mpmath.mpf(120)),
    ('S7', -1 / mpmath.mpf(5040)),
    ('C4', 1 / mpmath.mpf(24)),
    ('C6', -1 / mpmath.mpf(720)),
]:
    h, l = dd(v)
    out.append('pub const %s: (f64, f64) = (%s, %s);' % (name, lit(h), lit(l)))
print('\n'.join(out))
